import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const directory = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(directory, '..')
const manifestPath = path.join(root, 'packages/design-system/specs/edit-overlay-templates.json')
const jsOutput = path.join(root, 'packages/design-system/src/edit-overlay-spec.generated.js')
const cssOutput = path.join(root, 'packages/design-system/src/edit-overlay-spec.generated.css')
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
const { shared, templates } = manifest
const checkOnly = process.argv.includes('--check')

const jsSource = `/* Generated by scripts/generate-edit-overlay-spec.mjs. Do not edit directly. */
export const EDIT_OVERLAY_SPEC = Object.freeze(${JSON.stringify(manifest, null, 2)})
`

const cssSource = `/* Generated by scripts/generate-edit-overlay-spec.mjs. Do not edit directly. */
:root,
:host {
  --ds-edit-overlay-header-height: ${shared.headerHeight}px;
  --ds-edit-overlay-footer-height: ${shared.footerHeight}px;
  --ds-edit-overlay-padding-x: ${shared.surfacePaddingX}px;
  --ds-edit-overlay-header-padding-top: ${shared.headerPadding[0]}px;
  --ds-edit-overlay-header-padding-right: ${shared.headerPadding[1]}px;
  --ds-edit-overlay-header-padding-bottom: ${shared.headerPadding[2]}px;
  --ds-edit-overlay-header-padding-left: ${shared.headerPadding[3]}px;
  --ds-edit-overlay-footer-padding-y: ${shared.footerPadding[0]}px;
  --ds-edit-overlay-footer-padding-x: ${shared.footerPadding[1]}px;
  --ds-edit-overlay-footer-gap: ${shared.footerButtonGap}px;
  --ds-edit-field-label-width: ${shared.labelWidth}px;
  --ds-edit-field-control-gap: ${shared.labelControlGap}px;
  --ds-edit-field-gap: ${shared.fieldGap}px;
  --ds-edit-control-height: ${shared.controlHeight}px;
  --ds-edit-control-radius: ${shared.controlRadius}px;
  --ds-edit-modal-single-width: ${templates.singleModal.width}px;
  --ds-edit-modal-single-height: ${templates.singleModal.height}px;
  --ds-edit-modal-single-padding-y: ${templates.singleModal.contentPaddingY}px;
  --ds-edit-modal-double-width: ${templates.doubleModal.width}px;
  --ds-edit-modal-double-height: ${templates.doubleModal.height}px;
  --ds-edit-modal-double-padding-y: ${templates.doubleModal.contentPaddingY}px;
  --ds-edit-modal-double-column-min: ${templates.doubleModal.columnMinWidth}px;
  --ds-edit-modal-double-collapse-width: ${templates.doubleModal.collapseContentWidth}px;
  --ds-edit-modal-large-width: ${templates.largeModal.width}px;
  --ds-edit-modal-large-height: ${templates.largeModal.height}px;
  --ds-edit-modal-wide-width: ${templates.wideModal.width}px;
  --ds-edit-modal-wide-height: ${templates.wideModal.height}px;
  --ds-edit-drawer-width: ${templates.groupedDrawer.width}px;
  --ds-edit-group-gap: ${templates.groupedDrawer.groupGap}px;
  --ds-edit-group-content-gap: ${templates.groupedDrawer.groupContentGap}px;
  --ds-edit-group-title-height: ${templates.groupedDrawer.groupTitleHeight}px;
  --ds-edit-group-title-padding-y: ${templates.groupedDrawer.groupTitlePadding[0]}px;
  --ds-edit-group-title-padding-x: ${templates.groupedDrawer.groupTitlePadding[1]}px;
}

@container (max-width: ${templates.doubleModal.collapseContentWidth}px) {
  .ds-edit-form--2-column .ds-edit-form__grid {
    grid-template-columns: minmax(0, 1fr);
  }
}

@media (max-width: ${shared.compactFieldBreakpoint}px) {
  .ds-edit-field {
    grid-template-columns: minmax(0, 1fr);
    gap: var(--ds-space-1);
  }

  .ds-edit-field__label,
  .ds-edit-field--start .ds-edit-field__label {
    min-height: 20px;
    justify-content: flex-start;
    padding-top: 0;
    text-align: left;
  }
}
`

if (checkOnly) {
  const errors = []
  if (!fs.existsSync(jsOutput) || fs.readFileSync(jsOutput, 'utf8') !== jsSource) {
    errors.push(path.relative(root, jsOutput))
  }
  if (!fs.existsSync(cssOutput) || fs.readFileSync(cssOutput, 'utf8') !== cssSource) {
    errors.push(path.relative(root, cssOutput))
  }
  if (errors.length) {
    console.error(`Edit overlay generated files are stale: ${errors.join(', ')}`)
    process.exitCode = 1
  } else {
    console.log('Edit overlay generated files match the manifest.')
  }
} else {
  fs.writeFileSync(jsOutput, jsSource)
  fs.writeFileSync(cssOutput, cssSource)
  console.log('Generated edit overlay JS and CSS contracts.')
}
